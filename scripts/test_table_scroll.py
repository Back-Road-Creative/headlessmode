"""Every rendered table sits in a scroll box, so no page scrolls sideways on a phone.

On 2026-09-02 the first overflow-aware preview-shots run measured /rigscore/ at
1024px in a 390px viewport; two markdown tables in its documentation were the
whole cause. The fix is by construction — a table render hook and the
check-table shortcode both emit the wrapper — and this test is what notices a
future template that forgets it.

Reads public/, so it runs AFTER the Hugo build. It fails rather than skips when
public/ is missing, like test_systems_contract.py.

Run: hugo --configDir site-config --minify && pytest scripts/test_table_scroll.py -v
"""

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "public"
STYLE = ROOT / "themes" / "headlessmode" / "static" / "css" / "style.css"

# A table is wrapped when the nearest tag before it opens the scroll box. CI builds
# with --minify, which drops the attribute quotes (`class=table-scroll`), so the
# pattern accepts both spellings — the first CI run of this test failed on exactly that.
WRAPPED = re.compile(r'<div class=["\']?table-scroll["\']?[^>]*>\s*<table\b', re.S)
ANY_TABLE = re.compile(r"<table\b")


def _pages() -> list[Path]:
    assert PUBLIC.is_dir(), "public/ is missing — build the site first"
    return sorted(PUBLIC.rglob("index.html"))


def test_the_build_has_pages() -> None:
    assert _pages(), "no index.html under public/"


@pytest.mark.parametrize("page", _pages() if PUBLIC.is_dir() else [], ids=lambda p: str(p.relative_to(PUBLIC).parent) or ".")
def test_every_table_is_inside_a_scroll_box(page: Path) -> None:
    # The committed demo bundles under static/demo/ are generated by their
    # products and carry their own wrapper; this test is about the site's
    # templates.
    if "/demo/" in f"/{page.relative_to(PUBLIC).as_posix()}":
        pytest.skip("generated product bundle")
    html = page.read_text(encoding="utf-8")
    tables, wrapped = len(ANY_TABLE.findall(html)), len(WRAPPED.findall(html))
    assert tables == wrapped, f"{page.relative_to(PUBLIC)}: {tables} table(s), {wrapped} in a .table-scroll box"


def test_the_scroll_box_actually_scrolls() -> None:
    source = STYLE.read_text(encoding="utf-8")
    rule = re.search(r"\.table-scroll\s*\{([^}]*)\}", source)
    assert rule, "style.css has no .table-scroll rule"
    assert "overflow-x: auto" in rule.group(1), rule.group(0)
