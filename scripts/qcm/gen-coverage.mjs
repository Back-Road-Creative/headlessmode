#!/usr/bin/env node
// Generates data/quiet-corners-maps/coverage.json from the measured catalogue.
//
// Same shape as gen-headers.mjs, for the same reason: the answer to "can this map
// draw my state's land?" is decided by JS predicates (isBrowserFetchable, which
// folds in the licence refusal, and isSemanticallyUniform), and a Go template
// re-deriving them would be a second implementation free to drift from the first.
// So the JS computes and Hugo only renders.
//
//   node scripts/qcm/gen-coverage.mjs            # print
//   node scripts/qcm/gen-coverage.mjs --write    # write the file
import { writeFileSync } from 'node:fs';
import { STATE_CODES, MEASURED_ON, layerFor, licenceFor } from '../../themes/headlessmode/static/js/quiet-corners-maps/state-sources.js';
import { usableFamilies, FAMILY_LABEL } from '../../themes/headlessmode/static/js/quiet-corners-maps/source-land-boundaries.js';
import { DEFAULT_FAMILIES } from '../../themes/headlessmode/static/js/quiet-corners-maps/state-pages.js';

export const FILE = new URL('../../data/quiet-corners-maps/coverage.json', import.meta.url);

/** Why a family is absent, in the reader's terms. "No source" and "the publisher
 *  forbids it" are different facts, and a blank cell would tell neither. */
function absence(code, family) {
  const l = layerFor(code, family);
  if (!l || l.status === 'none') return 'none';
  if (licenceFor(l).redistribute === 'no') return 'licence';
  if (l.status === 'unverified') return 'unverified';
  return 'unusable';
}

/** One CHARACTER per family per state, not a nested object per cell.
 *  The nested form was 19 KB and a thousand lines of diff for a table nobody
 *  hand-edits; this is 51 short rows a reviewer can actually read, and the
 *  meaning lives in `legend` and the template rather than being repeated 153
 *  times. */
export const CODES = Object.freeze({ y: 'usable', n: 'none', l: 'licence', u: 'unverified', x: 'unusable' });
const LETTER = Object.freeze({ none: 'n', licence: 'l', unverified: 'u', unusable: 'x' });

export function coverage() {
  const families = [...DEFAULT_FAMILIES];
  const states = {};
  for (const code of STATE_CODES) {
    const usable = usableFamilies(code, families);
    states[code] = families.map((id) => (usable.includes(id) ? 'y' : LETTER[absence(code, id)])).join('');
  }
  return {
    _comment: 'GENERATED by scripts/qcm/gen-coverage.mjs from state-sources.json. Do not edit.',
    measuredOn: MEASURED_ON,
    families: families.map((id) => ({ id, label: FAMILY_LABEL[id] || id })),
    legend: CODES,
    states,
  };
}

const json = `${JSON.stringify(coverage(), null, 2)}\n`;
if (process.argv.includes('--write')) {
  writeFileSync(FILE, json);
  const n = Object.values(coverage().states).filter((s) => s.includes('y')).length;
  console.log(`wrote coverage for ${n} of ${STATE_CODES.length} states to data/quiet-corners-maps/coverage.json`);
} else if (import.meta.url === `file://${process.argv[1]}`) {
  process.stdout.write(json);
}
