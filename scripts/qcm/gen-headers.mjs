// Writes the Field Maps section of the BUILT public/_headers and the map page's policy <meta>
// from the two registries, so the CSP can never drift from the origins the app may use.
// The policy itself is a <meta http-equiv> (first child of <head>); the _headers rule only
// detaches the sitewide header. See mapsSection().
//
// Run:  node scripts/qcm/gen-headers.mjs --write-public   (after `hugo`; scripts/build-site.sh
//       does both, and scripts/test_headers_build_wiring.py holds every caller to it)
// Check: node --test scripts/qcm/headers-generated.test.mjs
//
// NOT COMMITTED, deliberately. The policy is one ~1,700-character line, so every branch
// that adds a map source rewrites that same line and any two such branches conflict on it
// — which on 2026-09-15 turned six mutually-disjoint layer PRs into six separate merge
// rounds, GitHub answering 422 to update-branch each time. A generated artifact kept out
// of git cannot be hand-merged wrong and cannot make two branches collide. static/_headers
// is now the hand-written prefix only; this section is appended to the build output.
//
// Why generated: 52 exact-path blocks is more than anyone will hand-edit correctly,
// and the whole point of the per-state split is that each page names ONLY its own
// state's origins. A hand-maintained list would rot on the first catalogue refresh.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { cspDirectivesFor } from '../../themes/headlessmode/static/js/quiet-corners-maps/source-registry.js';
import { mapRulePaths, stateOrigins } from '../../themes/headlessmode/static/js/quiet-corners-maps/state-pages.js';
import { hostSource, injectCspMeta } from './helpers/headers.mjs';

export const HEADERS_FILE = new URL('../../static/_headers', import.meta.url);
export const PUBLIC_HEADERS_FILE = new URL('../../public/_headers', import.meta.url);
export const PUBLIC_DIR = new URL('../../public/', import.meta.url);
export const SECTION_MARKER = '# Quiet Corners Field Maps';
const CSP = 'Content-Security-Policy';

/** The one CSP value for a page, given the extra connect-src origins it may reach. */
export function cspValue(extraOrigins = []) {
  const federal = cspDirectivesFor();
  // Emitted as bare host-sources: see hostSource() in helpers/headers.mjs. The
  // registries keep full origins because they are URLs; only the policy drops the scheme.
  const connect = [...new Set([...federal['connect-src'], ...extraOrigins].map(hostSource))].sort();
  return [
    "default-src 'self'",
    "script-src 'self'",
    "worker-src 'self' blob:",
    "style-src 'self' 'unsafe-inline'",
    "font-src 'self'",
    `img-src 'self' data: blob: ${federal['img-src'].map(hostSource).join(' ')}`,
    `connect-src 'self' ${connect.join(' ')}`,
    "frame-src 'none'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
  ].join('; ');
}

// Detach only. The policy is the page's <meta> (injectMapMeta below), so a header here would be
// intersected with it by the browser, and would put it back on a 2,000-character line.
const block = (path) => `${path}\n  ! ${CSP}\n`;

/** The whole generated section: ONE block, for the one map, which only DETACHES the sitewide CSP.
 *
 *  The map policy used to be a header on this block. Cloudflare caps a _headers line at 2,000
 *  characters and the policy had 164 left, so no new picture host could be added (spec U7,
 *  decision D3). It is now a <meta http-equiv> written into the built page by injectMapMeta()
 *  from the SAME cspValue(), as the first child of <head>. The "! " stays: without it the
 *  sitewide same-origin header would be served too and the browser enforces the INTERSECTION,
 *  which blocks every map service. A meta cannot carry frame-ancestors, report-uri, report-to
 *  or sandbox; the policy uses none (csp-meta.test.mjs holds that). */
export function mapsSection(origins = stateOrigins()) {
  const head = `${SECTION_MARKER} — GENERATED by scripts/qcm/gen-headers.mjs, do not hand-edit.
#
# ONE rule, for one map. The path is EXACT rather than a wildcard: Cloudflare
# applies every matching rule and joins a repeated header with a comma, which a
# browser enforces as the INTERSECTION of both policies, so an overlapping rule
# would quietly cut this one back rather than widen it.
#
# This rule only DETACHES the global same-origin policy ("! " has removed it on this
# path since 2026-04). The map's own policy is NOT a header: it is a <meta
# http-equiv="Content-Security-Policy"> that this same generator writes as the first
# child of <head> in the built page, from the same cspValue(), so it is not bound by
# the 2,000-character _headers line cap. \`npm run csp:headroom\` reports its length.
#
# A page with no rule here falls back to the global same-origin policy and can
# reach no map service at all — it fails closed, and loudly.
#
# ${origins.length} state origins; the policy is ${cspValue(origins).length} characters.
`;
  return `${head}\n${mapRulePaths().map((path) => block(path)).join('\n')}`;
}

/** The built page for a rule path: /quiet-corners/ -> public/quiet-corners/index.html. */
export const mapPageFile = (path) => new URL(`.${path}index.html`, PUBLIC_DIR);

/** Writes the policy <meta> into every built map page. Fails loudly when a page is missing:
 *  a map page with no meta and no header falls back to nothing it can reach. */
export function injectMapMeta(origins = stateOrigins()) {
  const policy = cspValue(origins);
  for (const path of mapRulePaths()) {
    const file = mapPageFile(path);
    if (!existsSync(file)) throw new Error(`gen-headers: ${path} was not built (${file.pathname}) -- run \`hugo\` first`);
    writeFileSync(file, injectCspMeta(readFileSync(file, 'utf8'), policy));
  }
  return policy.length;
}

/** `current` with the generated section appended, replacing one already there.
 *
 *  Idempotent on purpose: a build that runs the generator twice must not stack two
 *  copies of the policy, because Cloudflare applies EVERY matching rule and joins a
 *  repeated header with a comma, which a browser enforces as the INTERSECTION — a
 *  second copy would not be harmless duplication, it would cut the policy back. */
export function renderPublic(current, origins = stateOrigins()) {
  const i = current.indexOf(SECTION_MARKER);
  const prefix = i === -1 ? current : current.slice(0, i);
  return prefix + mapsSection(origins);
}

/** The policy as the BROWSER sees it: the committed prefix plus the generated section.
 *
 *  Every consumer that used to read static/_headers reads this instead. The file on disk
 *  is only half the answer now, and a test that read it directly would assert against a
 *  document no request ever receives. This needs no build to have run. */
export function effectiveHeaders(origins = stateOrigins()) {
  return renderPublic(readFileSync(HEADERS_FILE, 'utf8'), origins);
}

if (process.argv.includes('--write-public')) {
  // Fail LOUDLY rather than write a policy-less file. public/_headers exists only after
  // Hugo has copied static/ across; if it does not, the build order is wrong, and
  // shipping the hand-written prefix alone would leave every map page on the global
  // same-origin CSP — the dashboard would load and reach nothing.
  let current;
  try {
    current = readFileSync(PUBLIC_HEADERS_FILE, 'utf8');
  } catch (err) {
    console.error('gen-headers: public/_headers is missing — run `hugo` first (scripts/build-site.sh does).');
    process.exit(1);
  }
  writeFileSync(PUBLIC_HEADERS_FILE, renderPublic(current));
  const length = injectMapMeta();
  console.log(`wrote ${mapRulePaths().length} Field Maps rules (${stateOrigins().length} state origins) to public/_headers and the ${length}-character policy <meta> into ${mapRulePaths().join(', ')}`);
}
